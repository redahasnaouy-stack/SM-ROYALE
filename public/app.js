function renderDirectionalIcons(){
  const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);const nodes=[];while(walker.nextNode()){const n=walker.currentNode;if(n.textContent.includes('↗')&&!['SCRIPT','STYLE'].includes(n.parentElement.tagName)&&!n.parentElement.classList.contains('product-arrow'))nodes.push(n);}
  nodes.forEach(node=>{const parts=node.textContent.split('↗');const fragment=document.createDocumentFragment();parts.forEach((part,i)=>{fragment.append(document.createTextNode(part));if(i<parts.length-1){const icon=document.createElement('span');icon.className='inline-arrow';icon.setAttribute('aria-hidden','true');fragment.append(icon);}});node.replaceWith(fragment);});
}
